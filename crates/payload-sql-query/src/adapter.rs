//! The parts of the `DrizzleAdapter` (`@payloadcms/drizzle/src/types.ts`) and of
//! `adapter.payload` that the query builder reads.

use std::cell::Cell;
use std::sync::LazyLock;

use payload_engine::error::{EngineError, Result};
use payload_engine::js::JsVal;
use payload_engine::sql::schema::{RawSchema, RawTable};
use serde_json::Value as Json;

use crate::drizzle::{Decoder, DrizzleSchema};
use crate::operators::OperatorHandler;
use crate::sql::{Column, Expr, TableRef};

/// Adapter options that influence query building (`sqliteAdapter(args)` / `createDatabaseAdapter`).
#[derive(Clone, Debug)]
pub struct AdapterOptions {
  /// `adapter.name`: `sqlite` (only dialect generated by this crate).
  pub name: String,
  /// `adapter.idType`: `number` | `uuid` | `uuidv7` | `serial`.
  pub id_type: String,
  pub locales_suffix: String,
  pub relationships_suffix: String,
  pub versions_suffix: String,
  pub blocks_as_json: bool,
  pub limited_bound_parameters: bool,
  /// `adapter.operatorHandlers` (always `[]` for `@payloadcms/db-sqlite`).
  pub operator_handlers: Vec<OperatorHandler>,
}

impl Default for AdapterOptions {
  fn default() -> Self {
    Self {
      name: "sqlite".into(),
      id_type: "number".into(),
      locales_suffix: "_locales".into(),
      relationships_suffix: "_rels".into(),
      versions_suffix: "_v".into(),
      blocks_as_json: false,
      limited_bound_parameters: false,
      operator_handlers: Vec::new(),
    }
  }
}

impl AdapterOptions {
  /// Reads `{ idType, localesSuffix, relationshipsSuffix, versionsSuffix, blocksAsJSON, limitedBoundParameters }`.
  pub fn from_json(json: &Json) -> Self {
    let d = Self::default();
    let s = |k: &str, d: String| json.get(k).and_then(|v| v.as_str()).map(str::to_string).unwrap_or(d);
    let b = |k: &str| json.get(k).and_then(|v| v.as_bool()).unwrap_or(false);
    Self {
      name: s("name", d.name),
      id_type: s("idType", d.id_type),
      locales_suffix: s("localesSuffix", d.locales_suffix),
      relationships_suffix: s("relationshipsSuffix", d.relationships_suffix),
      versions_suffix: s("versionsSuffix", d.versions_suffix),
      blocks_as_json: b("blocksAsJSON"),
      limited_bound_parameters: b("limitedBoundParameters"),
      operator_handlers: Vec::new(),
    }
  }
}

/// Read-only adapter state for query building.
///
/// `config`, `collections` and `blocks` must come from the same decoded graph the
/// [`RawSchema`] was built from, so block identities line up with
/// `RawSchema::block_table_name_index`.
pub struct QueryAdapter<'a> {
  pub schema: &'a RawSchema,
  /// `adapter.tables`: the live drizzle tables (after `afterSchemaInit`), whose columns resolve
  /// `where` / `sort` paths and encode / decode their values. `None` reads them from
  /// `schema.raw_tables` (identical when no schema hook changed them).
  pub drizzle: Option<&'a DrizzleSchema>,
  /// `payload.config` (sanitized)
  pub config: &'a JsVal,
  /// `payload.collections`: `{ [slug]: { config, customIDType } }`
  pub collections: &'a JsVal,
  /// `payload.blocks`
  pub blocks: &'a JsVal,
  pub opts: AdapterOptions,
  alias_counter: Cell<u64>,
}

/// Stand-in for an `Object.prototype` member (`constructor`, `toString`, `__proto__`, ...) read
/// through a plain-object map such as `payload.collections[key]`: truthy, and every property the
/// query builder reads from it (`config`, `slug`, `customIDType`) is `undefined`.
static PROTO_MEMBER: LazyLock<JsVal> = LazyLock::new(|| JsVal::obj(Default::default()));

/// Keys that resolve to an `Object.prototype` member on a plain object without that own key.
pub fn is_object_prototype_key(key: &str) -> bool {
  matches!(
    key,
    "__proto__"
      | "constructor"
      | "__defineGetter__"
      | "__defineSetter__"
      | "__lookupGetter__"
      | "__lookupSetter__"
      | "hasOwnProperty"
      | "isPrototypeOf"
      | "propertyIsEnumerable"
      | "toLocaleString"
      | "toString"
      | "valueOf"
  )
}

/// `map[key]` on a plain JS object, including inherited `Object.prototype` members.
pub fn js_get<'v>(map: &'v JsVal, key: &str) -> &'v JsVal {
  match map.as_obj().and_then(|o| o.get(key)) {
    Some(v) => v,
    None if map.as_obj().is_some() && is_object_prototype_key(key) => &PROTO_MEMBER,
    None => map.get(key),
  }
}

/// `toSnakeCase(value)`: `to-snake-case` calls `string.toLowerCase()` on non-strings.
pub(crate) fn snake_case_of(v: &JsVal) -> Result<String> {
  match v {
    JsVal::Str(s) => Ok(payload_engine::strings::to_snake_case(s)),
    JsVal::Undefined => Err(read_undefined("toLowerCase")),
    JsVal::Null => Err(type_error("Cannot read properties of null (reading 'toLowerCase')")),
    _ => Err(type_error("string.toLowerCase is not a function")),
  }
}

pub(crate) fn type_error(message: impl Into<String>) -> EngineError {
  EngineError::new("TypeError", message)
}

pub(crate) fn read_undefined(prop: &str) -> EngineError {
  type_error(format!("Cannot read properties of undefined (reading '{prop}')"))
}

impl<'a> QueryAdapter<'a> {
  pub fn new(schema: &'a RawSchema, config: &'a JsVal, collections: &'a JsVal, blocks: &'a JsVal, opts: AdapterOptions) -> Self {
    Self { schema, config, collections, blocks, drizzle: None, opts, alias_counter: Cell::new(0) }
  }

  /// This adapter with `adapter.tables` read from the live drizzle schema.
  pub fn with_drizzle(mut self, drizzle: &'a DrizzleSchema) -> Self {
    self.drizzle = Some(drizzle);
    self
  }

  fn raw_table(&self, name: &str) -> Option<&RawTable> {
    self.schema.raw_tables.get(name).and_then(|t| t.as_ref())
  }

  /// `adapter.tables[name]`
  pub fn table(&self, name: Option<&str>) -> Option<TableRef> {
    let name = name?;
    if let Some(drizzle) = self.drizzle {
      let t = drizzle.tables.get(name)?;
      return Some(TableRef { name: t.db_name.clone(), alias: None });
    }
    let t = self.raw_table(name)?;
    Some(TableRef { name: t.name.clone(), alias: None })
  }

  /// `adapter.tables[name]` where the TS code then dereferences it.
  pub fn table_req(&self, name: Option<&str>, prop: &str) -> Result<TableRef> {
    self.table(name).ok_or_else(|| read_undefined(prop))
  }

  /// `table[key]`
  pub fn column(&self, table: &TableRef, key: &str) -> Option<Column> {
    let access_id = if table.alias.is_some() { Column::next_access_id() } else { 0 };
    if let Some(drizzle) = self.drizzle {
      let col = drizzle.table_by_db_name(&table.name)?.columns.get(key)?;
      return Some(Column {
        table: table.clone(),
        key: key.to_string(),
        name: col.name.clone(),
        decoder: col.decoder,
        to_driver: col.to_driver,
        primary: col.primary,
        access_id,
      });
    }
    let raw = self.raw_table(&table.name)?;
    let col = raw.columns.get(key)?;
    Some(Column {
      table: table.clone(),
      key: key.to_string(),
      name: col.get("name").and_then(|v| v.as_str()).unwrap_or(key).to_string(),
      decoder: Decoder::from_raw_type(col.get("type").and_then(|v| v.as_str()).unwrap_or("")),
      to_driver: None,
      primary: col.get("primaryKey").is_some_and(|v| v.as_bool() == Some(true)),
      access_id,
    })
  }

  /// The key of the column named `column` (database name) of the table whose database name is
  /// `table`.
  pub fn column_key_by_db_name(&self, table: &str, column: &str) -> Option<String> {
    if let Some(drizzle) = self.drizzle {
      let t = drizzle.table_by_db_name(table)?;
      return t.columns.iter().find(|(_, c)| c.name == column).map(|(key, _)| key.clone());
    }
    let t = self.schema.raw_tables.values().flatten().find(|t| t.name == table)?;
    t.columns.iter().find(|(key, c)| c.get("name").and_then(|n| n.as_str()).unwrap_or(key) == column).map(|(key, _)| key.clone())
  }

  /// `table[key]` as an expression (`undefined` when the column does not exist).
  pub fn col(&self, table: &TableRef, key: &str) -> Option<Expr> {
    self.column(table, key).map(Expr::Col)
  }

  /// `table?.[key]` on a possibly undefined table, throwing like JS when the table is undefined.
  pub fn col_of(&self, table: Option<&TableRef>, key: &str) -> Result<Option<Expr>> {
    let table = table.ok_or_else(|| read_undefined(key))?;
    Ok(self.col(table, key))
  }

  /// `adapter.tableNameMap.get(key)`
  pub fn table_name_map(&self, key: &str) -> Option<String> {
    self.schema.table_name_map.get(key).cloned()
  }

  /// `getTableAlias({ adapter, tableName })`: `alias(adapter.tables[tableName], toSnakeCase(uuid()))`.
  pub fn get_table_alias(&self, table_name: Option<&str>) -> Result<(TableRef, String)> {
    let table = self.table(table_name).ok_or_else(|| type_error("Cannot create proxy with a non-object as target or handler"))?;
    let n = self.alias_counter.get() + 1;
    self.alias_counter.set(n);
    // Same shape as a snake-cased v4 uuid, always starting with a letter.
    let alias = format!("a{:07x}_0000_4000_8000_{:012x}", n, n);
    Ok((TableRef { name: table.name, alias: Some(alias.clone()) }, alias))
  }

  /// `aliasedTable(adapter.tables[tableName], alias)`
  pub fn aliased_table(&self, table_name: &str, alias: &str) -> Result<TableRef> {
    let table = self.table_req(Some(table_name), "id")?;
    Ok(TableRef { name: table.name, alias: Some(alias.to_string()) })
  }

  /// `adapter.payload.config.localization` (falsy when disabled).
  pub fn localization(&self) -> &JsVal {
    self.config.get("localization")
  }

  /// `adapter.payload.config.localization.localeCodes`
  pub fn locale_codes(&self) -> Vec<String> {
    self.localization().get("localeCodes").items().filter_map(|v| v.as_str().map(str::to_string)).collect()
  }

  /// `adapter.payload.collections[slug]`
  pub fn collection(&self, slug: &JsVal) -> Result<&'a JsVal> {
    let c = self.collection_or_undefined(slug);
    if c.is_undefined() { Err(read_undefined("config")) } else { Ok(c) }
  }

  /// `adapter.payload.collections[slug]` (`undefined` when missing).
  pub fn collection_or_undefined(&self, slug: &JsVal) -> &'a JsVal {
    js_get(self.collections, &crate::js_ops::js_string(slug))
  }

  /// `adapter.payload.collections[slug].config`, throwing like the caller's next property read.
  pub fn collection_config(&self, slug: &JsVal) -> Result<&'a JsVal> {
    self.collection_config_read(slug, "flattenedFields")
  }

  /// `adapter.payload.collections[slug].config.<prop>`: the error names `prop` when `config`
  /// is `undefined`.
  pub fn collection_config_read(&self, slug: &JsVal, prop: &str) -> Result<&'a JsVal> {
    let config = self.collection(slug)?.get("config");
    if config.is_undefined() { Err(read_undefined(prop)) } else { Ok(config) }
  }

  /// `adapter.payload.blocks[slug]`
  pub fn block(&self, slug: &JsVal) -> &'a JsVal {
    js_get(self.blocks, &crate::js_ops::js_string(slug))
  }

  /// `isUUIDType(adapter.idType)`
  pub fn is_uuid_id(&self) -> bool {
    matches!(self.opts.id_type.as_str(), "uuid" | "uuidv7")
  }

  /// `resolveBlockTableName(block, originalTableName)`
  pub fn resolve_block_table_name(&self, block: &JsVal, original: Option<String>) -> String {
    let original = original.unwrap_or_else(|| "undefined".into());
    match block.identity().and_then(|id| self.schema.block_table_name_index.get(&id)) {
      Some(index) if *index != 0 => format!("{original}_{index}"),
      _ => original,
    }
  }

  /// `getCollectionIdType({ adapter, collection })`
  pub fn collection_id_type(&self, collection: &JsVal) -> Option<String> {
    let custom = collection.get("customIDType");
    if !custom.is_nullish() {
      return Some(crate::js_ops::js_string(custom));
    }
    match self.opts.id_type.as_str() {
      "number" | "serial" => Some("number".into()),
      "text" | "uuid" | "uuidv7" => Some("text".into()),
      _ => None,
    }
  }
}
