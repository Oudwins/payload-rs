#!/usr/bin/env node
/**
 * Turns a vitest JSON report (default .rs-baseline/sqlite-all.json) into a
 * markdown summary (default .rs-baseline/summary.md): totals, per-file
 * pass/fail/skip counts, failing test names (+ first line of the failure) and
 * files that failed to load.
 *
 *   node packages/engine-rs/scripts/summarizeBaseline.mjs [input.json] [output.md]
 */
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '../../..')
const input = path.resolve(process.argv[2] ?? path.join(root, '.rs-baseline/sqlite-all.json'))
const output = path.resolve(process.argv[3] ?? path.join(path.dirname(input), 'summary.md'))

if (!fs.existsSync(input)) {
  console.error(`No report at ${input}`)
  process.exit(1)
}

const report = JSON.parse(fs.readFileSync(input, 'utf8'))
const rel = (file) => path.relative(root, file)
const firstLine = (text) =>
  String(text ?? '')
    // eslint-disable-next-line no-control-regex
    .replace(/\u001b\[[0-9;]*m/g, '')
    .split('\n')
    .find((line) => line.trim())
    ?.trim()
    .slice(0, 200) ?? ''
const escapeCell = (text) => String(text).replaceAll('|', '\\|')

const files = report.testResults
  .map((file) => {
    const counts = { failed: 0, passed: 0, skipped: 0, todo: 0 }
    const failures = []
    for (const test of file.assertionResults) {
      if (test.status === 'passed') {
        counts.passed++
      } else if (test.status === 'failed') {
        counts.failed++
        failures.push({ message: firstLine(test.failureMessages?.[0]), name: test.fullName })
      } else if (test.status === 'todo') {
        counts.todo++
      } else {
        counts.skipped++
      }
    }
    return {
      counts,
      failures,
      file: rel(file.name),
      loadError:
        file.assertionResults.length === 0 && file.status === 'failed'
          ? firstLine(file.message)
          : '',
      status: file.status,
    }
  })
  .sort((a, b) => a.file.localeCompare(b.file))

const total = files.reduce(
  (acc, f) => {
    for (const key of Object.keys(acc)) {
      acc[key] += f.counts[key]
    }
    return acc
  },
  { failed: 0, passed: 0, skipped: 0, todo: 0 },
)

const lines = []
lines.push('# Int suite baseline summary', '')
lines.push(
  `Source: \`${rel(input)}\` (generated by packages/engine-rs/scripts/summarizeBaseline.mjs)`,
)
if (report.startTime) {
  lines.push(`Run started: ${new Date(report.startTime).toISOString()}`)
}
lines.push('')
lines.push('| | count |', '|---|---|')
lines.push(`| test files | ${files.length} |`)
lines.push(`| files passed | ${files.filter((f) => f.status === 'passed').length} |`)
lines.push(`| files failed | ${files.filter((f) => f.status === 'failed').length} |`)
lines.push(
  `| files fully skipped (0 passed, 0 failed) | ${files.filter((f) => f.counts.passed + f.counts.failed === 0).length} |`,
)
lines.push(`| tests passed | ${total.passed} |`)
lines.push(`| tests failed | ${total.failed} |`)
lines.push(`| tests skipped | ${total.skipped} |`)
lines.push(`| tests todo | ${total.todo} |`)
lines.push('')

lines.push('## Per file', '')
lines.push('| file | status | passed | failed | skipped | todo |', '|---|---|---|---|---|---|')
for (const f of files) {
  lines.push(
    `| ${f.file} | ${f.status} | ${f.counts.passed} | ${f.counts.failed} | ${f.counts.skipped} | ${f.counts.todo} |`,
  )
}
lines.push('')

const loadErrors = files.filter((f) => f.loadError)
if (loadErrors.length) {
  lines.push('## Files that failed before running tests', '')
  for (const f of loadErrors) {
    lines.push(`- \`${f.file}\`: ${escapeCell(f.loadError)}`)
  }
  lines.push('')
}

lines.push('## Failing tests', '')
for (const f of files.filter((f) => f.failures.length)) {
  lines.push(`### ${f.file} (${f.failures.length})`, '')
  for (const failure of f.failures) {
    lines.push(
      `- ${failure.name}${failure.message ? ` — \`${failure.message.replaceAll('`', "'")}\`` : ''}`,
    )
  }
  lines.push('')
}

fs.mkdirSync(path.dirname(output), { recursive: true })
fs.writeFileSync(output, `${lines.join('\n')}\n`)
console.log(
  `${rel(output)}: ${files.length} files, ${total.passed} passed, ${total.failed} failed, ${total.skipped} skipped`,
)
