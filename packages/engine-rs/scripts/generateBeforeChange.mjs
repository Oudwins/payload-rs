const rewriteImports = (source) =>
  source.replace(/(from\s+')(\.[^']+)(')/g, (match, before, specifier, after) => {
    if (localModules.has(specifier)) {
      return match
    }
    if (replacedModules[specifier]) {
      return `${before}${replacedModules[specifier]}${after}`
    }
    const target = path.resolve(upstreamDir, specifier)
    let relative = path.relative(outDir, target).split(path.sep).join('/')
    if (!relative.startsWith('.')) {
      relative = `./${relative}`
    }
    return `${before}${relative}${after}`
  })

let isStale = false
for (const [name, list] of Object.entries(patches)) {
  let source = fs.readFileSync(path.join(upstreamDir, name), 'utf8')
  source = rewriteImports(source)
  for (const [from, to] of list) {
    const count = source.split(from).length - 1
    if (count !== 1) {
      console.error(`generateBeforeChange: patch for ${name} matches ${count} times:\n${from}`)
      process.exit(1)
    }
    source = source.replace(from, to)
  }
  const file = path.join(outDir, name)
  // formatted like the rest of the repository (oxfmt.config.ts)
  const output = execFileSync(
    path.join(root, 'node_modules/.bin/oxfmt'),
    [`--stdin-filepath=${path.relative(root, file)}`],
    { cwd: root, encoding: 'utf8', input: header(name) + source },
  )
  if (isCheck) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== output) {
      console.error(`generateBeforeChange: ${path.relative(root, file)} is out of date`)
      isStale = true
    }
  } else {
    fs.mkdirSync(outDir, { recursive: true })
    fs.writeFileSync(file, output)
    console.log(`wrote ${path.relative(root, file)}`)
  }
}
process.exit(isStale ? 1 : 0)
