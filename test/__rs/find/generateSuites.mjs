// Generates one differential spec per upstream int suite under test/__rs/find/suites/<suite>/.
// Each spec installs the harness and then runs the upstream suite unchanged, so every find the
// upstream tests perform is replayed through the Rust port.
// Usage: node test/__rs/find/generateSuites.mjs [suite...]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const dirname = path.dirname(fileURLToPath(import.meta.url))
const defaults = ['fields', 'joins', 'localization', 'relationships', 'select', 'versions']
const suites = process.argv.slice(2).length ? process.argv.slice(2) : defaults

for (const suite of suites) {
  const dir = path.join(dirname, 'suites', suite)
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(
    path.join(dir, 'config.ts'),
    `// Generated by test/__rs/find/generateSuites.mjs\nexport { default } from '../../../../${suite}/config.js'\n`,
  )
  fs.writeFileSync(
    path.join(dir, 'find.int.spec.ts'),
    `// Generated by test/__rs/find/generateSuites.mjs
import { vi } from 'vitest'

import { installFindHarness } from '../../harness.js'

vi.mock('../../../../../packages/drizzle/src/find/buildFindManyArgs.js', async (importOriginal) => {
  const mod = await importOriginal<any>()
  const { wrapBuildFindManyArgs } = await import('../../bridge.js')
  return { ...mod, buildFindManyArgs: wrapBuildFindManyArgs(mod.buildFindManyArgs) }
})

vi.mock('../../../../../packages/drizzle/src/find/findMany.js', async (importOriginal) => {
  const mod = await importOriginal<any>()
  const { wrapFindMany } = await import('../../bridge.js')
  return { ...mod, findMany: wrapFindMany(mod.findMany) }
})

installFindHarness('${suite}')

await import('../../../../${suite}/int.spec.js')
`,
  )
}
